def cell_center(row, col):
    """Clip-space centre of a grid cell."""
    return -1.0 + (col + 0.5) * CELL_SIZE, 1.0 - (row + 0.5) * CELL_SIZE


def cell_at(x, y):
    """(row, col) of the cell containing a clip-space point. The column can be
    outside the grid for points past the left or right edge."""
    return math.floor((1.0 - y) / CELL_SIZE), math.floor((x + 1.0) / CELL_SIZE)


